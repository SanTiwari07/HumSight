"""Run the agent on demo clips and write the traces to docs/example_trace.md.

    python scripts/make_demo_clips.py
    python scripts/export_trace.py

Evidence for the Agentic Vision award: each step shows which measured number led to the next call.
Nothing is written by hand; the file is regenerated from real runs.
"""
import json
import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from humsight import env  # noqa: E402
from humsight.agent.loop import run_agent  # noqa: E402
from humsight.agent.state import JobParams, JobState  # noqa: E402
from humsight.agent.tools import compact  # noqa: E402
from humsight.io import load_video  # noqa: E402
from humsight.pipeline import run_fixed  # noqa: E402

CASES = [
    ("pump_shake_fault", "Hidden 58.5 Hz fault under 3.5 Hz camera shake: shake is measured, compensated, rejected, and the fault is isolated."),
    ("shake_only", "Healthy machine, shaky camera: the only peak is shake, so the correct answer is NO_FAULT."),
    ("alias_130hz", "Expected frequency above 0.45 x fps: the agent stops and asks for a faster recording (human in the loop)."),
]


def fmt_result(r: dict) -> str:
    skip = {"runtime_ms", "alias", "work_order"}
    small = compact({k: v for k, v in r.items() if k not in skip}, max_bytes=700)
    return json.dumps(small, ensure_ascii=False)


def main():
    out = [f"# Example agent traces", "",
           "Generated by `python scripts/export_trace.py` from real runs on the synthetic demo clips "
           f"(`{env.banner()}`). Source labels show who chose each call (`rules` = deterministic policy, "
           "`llm` = Gemini). Numbers come from OpenCV/NumPy tools only.", ""]
    for demo, blurb in CASES:
        meta = json.load(open(os.path.join(ROOT, "demo_clips", demo, "demo.json"), encoding="utf-8"))
        clip = load_video(os.path.join(ROOT, "demo_clips", demo, "clip.npz"), meta["fps"])
        with tempfile.TemporaryDirectory() as d:
            st = JobState(clip, JobParams(policy="rules", render=False, workers=os.cpu_count() or 1,
                                          **{k: v for k, v in meta.get("params", {}).items()}), d)
            r = run_agent(st)
            fixed = run_fixed(clip, d, render=False) if demo != "alias_130hz" else None
        out += [f"## {meta['title']}", "", blurb, "",
                f"**Verdict: {r['verdict']}** after {r['n_tool_calls']} tool calls in {r['runtime_s']} s. {r['summary']}", ""]
        out += ["| # | tool | arguments | why (agent) | measured result |", "|---|---|---|---|---|"]
        for e in r["trace"]:
            if e["kind"] != "tool":
                out.append(f"| | _note_ | | {e['rationale']} | |")
                continue
            res = fmt_result(e["result"]).replace("|", "\\|")
            args = json.dumps(e["args"]).replace("|", "\\|")
            out.append(f"| {e['step']} | `{e['tool']}` | `{args}` | {e['rationale'].replace('|', '/')} | `{res}` |")
        if fixed:
            f = fixed["findings"][0] if fixed["findings"] else None
            out += ["", "Fixed pipeline on the same clip: "
                    + (f"**{fixed['verdict']}** at {f['f_hz']} Hz ({f['amp_px']} px), no shake check, "
                       "no review path." if f else f"**{fixed['verdict']}**."), ""]
        else:
            out.append("")
    path = os.path.join(ROOT, "docs", "example_trace.md")
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
